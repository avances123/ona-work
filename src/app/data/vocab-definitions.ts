export function normalizeVocabWord(raw: string): string {
  return raw
    .trim()
    .replace(/^[.,;:¡!¿?"'«»()—\-]+|[.,;:¡!¿?"'«»()—\-]+$/g, '')
    .toLowerCase();
}

export function findVocabDefinition(word: string, customDefinition?: string): string | null {
  if (customDefinition && customDefinition.trim().length > 0) {
    return customDefinition.trim();
  }

  const normalized = normalizeVocabWord(word);
  if (!normalized) return null;

  if (VOCAB_DEFINITIONS[normalized]) {
    return VOCAB_DEFINITIONS[normalized];
  }

  // Intentos sencillos de plural / género
  const candidates: string[] = [];
  if (normalized.endsWith('es') && normalized.length > 4) {
    candidates.push(normalized.slice(0, -2));
  }
  if (normalized.endsWith('s') && normalized.length > 3) {
    candidates.push(normalized.slice(0, -1));
  }
  if (normalized.endsWith('a') && normalized.length > 3) {
    candidates.push(normalized.slice(0, -1) + 'o');
  }
  if (normalized.endsWith('o') && normalized.length > 3) {
    candidates.push(normalized.slice(0, -1) + 'a');
  }

  for (const c of candidates) {
    if (VOCAB_DEFINITIONS[c]) {
      return VOCAB_DEFINITIONS[c];
    }
  }

  return null;
}

export function getDistractorDefinitions(correctDefinition: string, count: number): string[] {
  const pool = Array.from(new Set(Object.values(VOCAB_DEFINITIONS))).filter(
    (def) => def !== correctDefinition
  );

  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }

  return pool.slice(0, count);
}
